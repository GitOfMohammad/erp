const { Router } = require('express')
const authenticate = require('../../core/middlewares/authenticate')
const authorize = require('../../core/middlewares/authorization')
const validate = require('../../core/middlewares/schemaValidator')
const Upload = require('../../core/utils/upload')
const ErrorApi = require('../../core/api/ErrorApi')
const controller = require('./settings.controller')
const { companyGeneralSchema, taxSettingsSchema, moadianSettingsSchema, financeSettingsSchema, inventorySettingsSchema, securitySettingsSchema, printSettingsSchema } = require('./settings.validator')

const router = Router()
router.use(authenticate)
const validateMediaKind = (req, res, next) => ['logo', 'stamp'].includes(req.params.kind) ? next() : next(ErrorApi.notFound('نوع تصویر تنظیمات پیدا نشد'))

router.get('/general', authorize('settings.general.read'), controller.getGeneral)
router.put('/general', authorize('settings.general.update'), validate(companyGeneralSchema), controller.saveGeneral)
router.get('/tax', authorize('settings.tax.read'), controller.getTax)
router.put('/tax', authorize('settings.tax.update'), validate(taxSettingsSchema), controller.saveTax)
router.get('/moadian', authorize('settings.tax.read'), controller.getMoadian)
router.put('/moadian', authorize('settings.tax.update'), validate(moadianSettingsSchema), controller.saveMoadian)
router.get('/finance', authorize('settings.finance.read'), controller.getFinance)
router.put('/finance', authorize('settings.finance.update'), validate(financeSettingsSchema), controller.saveFinance)
router.get('/inventory', authorize('settings.inventory.read'), controller.getInventory)
router.get('/inventory/defaults', authorize('inventory.read'), controller.getInventoryDefaults)
router.put('/inventory', authorize('settings.inventory.update'), validate(inventorySettingsSchema), controller.saveInventory)
router.get('/security', authorize('settings.security.read'), controller.getSecurity)
router.put('/security', authorize('settings.security.update'), validate(securitySettingsSchema), controller.saveSecurity)
router.get('/print', authorize('settings.general.read'), controller.getPrint)
router.put('/print', authorize('settings.general.update'), validate(printSettingsSchema), controller.savePrint)
router.get('/print/default/:type', controller.getDefaultPrint)
router.get('/finance/currencies', controller.getFinanceCurrencies)
router.get('/general/media/:kind', authorize('settings.general.read'), validateMediaKind, controller.getMedia)
router.post('/general/media/:kind', authorize('settings.general.update'), validateMediaKind, Upload.privateImage('company', 'image'), controller.uploadMedia)
router.delete('/general/media/:kind', authorize('settings.general.update'), validateMediaKind, controller.clearMedia)

module.exports = router
